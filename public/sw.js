/* Service worker: recibe notificaciones PUSH incluso cuando la pestaña no está abierta. */
self.addEventListener("push", (event) => {
  let data = {};
  try { data = event.data ? event.data.json() : {}; } catch { data = { body: event.data ? event.data.text() : "" }; }
  const title = data.title || "CRM-SICOVEN";
  const options = {
    body: data.body || "Hay novedades en los reportes de pago.",
    icon: "/favicon.ico",
    badge: "/favicon.ico",
    tag: data.tag || "sicoven-payment-report",
    data: { url: data.url || "/comercializacion" },
    renotify: true
  };
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const target = new URL(event.notification.data?.url || "/comercializacion", self.location.origin).href;
  event.waitUntil((async () => {
    const windows = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
    for (const client of windows) {
      if (client.url.startsWith(self.location.origin) && "focus" in client) {
        await client.focus();
        if ("navigate" in client) await client.navigate(target);
        return;
      }
    }
    await self.clients.openWindow(target);
  })());
});
